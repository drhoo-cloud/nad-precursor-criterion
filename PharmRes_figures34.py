matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

# ----------------------------------------------------------------- parameters
K_S, K_I = 29.0, 175.0
N_UN, N_DP, M0 = 100.0, 25.0, 30.0
ETA = 0.34                      # highest published elasticity

FONT = "Nimbus Sans"            # Helvetica-metric; substitute if unavailable
FS   = 8.0                      # >= 7 pt at final printed size
W = 190/25.4                    # print width, inches (190 mm)
AC, BC, GY, LG = "#1f6fb4", "#b81f2e", "#555555", "#8c8c8c"
SHADE, GREY = "#dce9f5", "#ececec"

plt.rcParams.update({
    "font.family": FONT, "font.size": FS,
    "axes.labelsize": 11, "axes.titlesize": 11,
    "xtick.labelsize": 11, "ytick.labelsize": 11,
    "legend.fontsize": FS, "axes.linewidth": 0.9,
    "svg.fonttype": "none", "ps.fonttype": 42, "pdf.fonttype": 42,
})

import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "figures") + os.sep
os.makedirs(OUT, exist_ok=True)


def save(fig, stem):
    fig.savefig(OUT + "PharmRes_" + stem + ".eps", format="eps", bbox_inches="tight")
    fig.savefig(OUT + "PharmRes_" + stem + ".tif", format="tiff", dpi=600,
                bbox_inches="tight", pil_kwargs={"compression": "tiff_lzw"})
    fig.savefig(OUT + "PharmRes_" + stem + ".png", dpi=150, bbox_inches="tight")
    plt.close(fig)


def sat(N):                     # fractional saturation of SIRT1
    return N / (K_S + N)


def gain(N, N0):                # G(N) relative to the resting state
    return sat(N) / sat(N0)


def penalty(M):                 # P(M), exit penalty
    return (1.0 + M0 / K_I) / (1.0 + M / K_I)


def eta_req(M, N0):
    return M * (K_S + N0) / (K_S * (K_I + M))


G_UN, G_DP = (K_S + N_UN) / N_UN, (K_S + N_DP) / N_DP          # 1.29, 2.16
M_UN = K_I * (G_UN * (1 + M0 / K_I) - 1)                       # 89
M_DP = K_I * (G_DP * (1 + M0 / K_I) - 1)                       # 268


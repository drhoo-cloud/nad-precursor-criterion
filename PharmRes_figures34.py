"""
PharmRes manuscript -- the model, and Figures 3 and 4.

Parameter dictionary (single source of truth for every computed value):
    K_S = 29  uM   SIRT1 Michaelis constant for NAD+ (acetyl-H3K9)
    K_i = 175 uM   SIRT1 inhibition constant for nicotinamide (IC50 = Ki)
    N0  = 100 uM   nuclear free NAD+, unstressed
    N_d = 25  uM   nuclear free NAD+, assumed fourfold depletion
    M0  = 30  uM   resting intracellular nicotinamide

Output: figures are drawn at 190 mm (Elsevier full-page width) with 8 pt text,
above the 7 pt minimum at final printed size. Line artwork is written as EPS
(vector) with a 600 dpi TIFF alongside.

Figure 1 of the manuscript is generated by PharmRes_Figure1.py.
Figure 2 is a hand-drawn pathway schematic and has no generating script.
"""
import numpy as np

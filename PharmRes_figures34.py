# =========================================================== FIGURE 3
Ml = np.logspace(np.log10(M0), 3, 700)


def out_ratio(M, N0):
    N = N0 * (M / M0) ** ETA
    return gain(N, N0) * penalty(M)


def fig4a(ax):
    yu, yd = out_ratio(Ml, N_UN), out_ratio(Ml, N_DP)
    ax.fill_between(Ml, yu, 1.0, color=SHADE, zorder=0)
    ax.semilogx(Ml, yu, color=AC, lw=2.4, label="unstressed  $N_0$ = 100 \u00b5M")
    ax.semilogx(Ml, yd, color=BC, lw=2.6, ls="--",
                label="UV-depleted  $N_0$ = 25 \u00b5M")
    ax.axhline(1.0, color=GY, lw=1.0)
    Mp = Ml[np.argmax(yd)]
    ax.plot([Mp], [yd.max()], "o", ms=10, mfc="white", mec=BC, mew=2.0, zorder=5)
    for M, y, c, txt, dy in ((100, out_ratio(100, N_UN), AC, "\u221219%", -0.075),
                             (100, out_ratio(100, N_DP), BC, "\u22129%", 0.055)):
        ax.plot([M], [y], "o", ms=8, color=c, zorder=5)
        ax.text(118, y + dy, txt, fontsize=FS, color=c, weight="bold")
    ax.text(32, 1.11, "resting $M_0$ = 30 \u00b5M", fontsize=FS-0.5, color="0.40",
            va="top")
    ax.text(760, 0.62, "shortfall against\nbaseline output", fontsize=FS-0.5,
            color="0.40", style="italic", ha="right")
    ax.set_xlim(M0, 1000); ax.set_ylim(0.3, 1.14)
    ax.set_xlabel("Intracellular nicotinamide, $M$ (\u00b5M)")
    ax.set_ylabel("Sirtuin output, $A/A_0$")
    ax.set_title("(a) what the dose delivers", loc="left", fontsize=FS)
    ax.legend(frameon=False, loc="lower left", fontsize=FS-0.5, handlelength=1.9)


def fig4b(ax):
    Mb = np.logspace(0, np.log10(260), 700)
    eu, ed = eta_req(Mb, N_UN), eta_req(Mb, N_DP)
    ax.fill_between(Mb, 0, ed, color=GREY, zorder=0)
    ax.semilogx(Mb, eu, color=AC, lw=2.4)
    ax.semilogx(Mb, ed, color=BC, lw=2.6, ls="--")
    ax.axvline(M0, color="0.6", lw=1.0, ls=":")
    ax.text(1.12, 1.36, "measured \u03b7", fontsize=FS-0.5, color="0.35",
            style="italic")
    for eta, c, lab, ty in ((0.34, BC, "riboside, blood  0.34", 1.22),
                            (0.26, GY, "NAMPT 6\u00d7  0.26", 1.09),
                            (0.00, BC, "keratinocytes  0.00", 0.96)):
        ax.axhline(eta, color=c, lw=1.2)
        ax.text(1.12, ty, lab, fontsize=FS-0.5, color=c)
        if eta > 0:
            for N0, cc in ((N_UN, AC), (N_DP, BC)):
                Mi = eta * K_S * K_I / ((K_S + N0) - eta * K_S)
                ax.plot([Mi], [eta], "o", ms=9, mfc="white", mec=cc, mew=1.8,
                        zorder=5)
    ax.text(235, 0.70, "condition unmet\nin either state", fontsize=FS-0.5,
            color="0.40", style="italic", va="top", ha="right")
    ax.text(31, 2.30, "resting $M_0$", fontsize=FS-0.5, color="0.40", va="top")
    ax.text(3.4, 2.28, "threshold, unstressed", fontsize=FS, color=AC, va="top")
    ax.text(95, 1.30, "threshold,\nUV-depleted", fontsize=FS, color=BC)
    ax.set_xlim(1, 260); ax.set_ylim(0, 2.45)
    ax.set_xlabel("Intracellular nicotinamide, $M$ (\u00b5M)")
    ax.set_ylabel("Elasticity $\\eta$")
    ax.set_title("(b) what it would have to deliver", loc="left", fontsize=FS)


for stem, fn in (("Figure4a", fig4a), ("Figure4b", fig4b)):
    f, a = plt.subplots(figsize=(W, W * 0.52))
